"""Client -> server messages. Server -> client messages are plain dicts with `type`."""

import json
from typing import Annotated, Any, Literal

from pydantic import BaseModel, Field, TypeAdapter, field_validator

MAX_PROPS_BYTES = 64_000
Color = Annotated[str, Field(pattern=r"^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$")]
Id = Annotated[str, Field(min_length=1, max_length=36)]


class _Msg(BaseModel):
    rid: str | None = None  # client request id, echoed back in errors


class PlayerInfo(BaseModel):
    id: Id
    name: Annotated[str, Field(min_length=1, max_length=60)]
    color: Color
    is_gm: bool = False


class Hello(_Msg):
    type: Literal["hello"]
    player: PlayerInfo


class PlayerSettings(BaseModel):
    wheel: Literal["zoom", "pan"] | None = None
    chat_timestamps: bool | None = None


class PlayerUpdate(_Msg):
    type: Literal["player.update"]
    name: Annotated[str, Field(min_length=1, max_length=60)] | None = None
    color: Color | None = None
    settings: PlayerSettings | None = None


class GameSettings(_Msg):
    type: Literal["game.settings"]
    measurement: Literal["metric", "imperial"] | None = None


class PageView(_Msg):
    type: Literal["page.view"]
    page_id: Id


class PagePatch(BaseModel):
    name: Annotated[str, Field(min_length=1, max_length=120)] | None = None
    sort_order: float | None = None
    archived: bool | None = None
    width: Annotated[int, Field(ge=1, le=500)] | None = None
    height: Annotated[int, Field(ge=1, le=500)] | None = None
    grid_size: Annotated[int, Field(ge=10, le=500)] | None = None
    grid_type: Literal["square", "hex_v", "hex_h", "none"] | None = None
    grid_color: Color | None = None
    grid_opacity: Annotated[float, Field(ge=0, le=1)] | None = None
    snap: bool | None = None
    scale_number: Annotated[float, Field(gt=0)] | None = None
    scale_unit: Annotated[str, Field(min_length=1, max_length=12)] | None = None
    diagonal_rule: Literal["5e", "pf", "euclid", "manhattan"] | None = None
    background_color: Color | None = None


class PageCreate(_Msg):
    type: Literal["page.create"]
    page: PagePatch = PagePatch()


class PageUpdate(_Msg):
    type: Literal["page.update"]
    id: Id
    patch: PagePatch


class PageDelete(_Msg):
    type: Literal["page.delete"]
    id: Id


class PageDuplicate(_Msg):
    type: Literal["page.duplicate"]
    id: Id


class SetPlayerPage(_Msg):
    type: Literal["game.player_page"]
    page_id: Id
    # None = move everyone (clears overrides); otherwise move one player.
    player_id: Id | None = None


class ObjectData(BaseModel):
    """Full object for creation; id is generated by the client for instant feedback."""

    id: Id
    page_id: Id
    kind: Literal["token", "image", "path", "text", "template"]
    layer: Literal["map", "objects", "gm"] = "objects"
    x: float
    y: float
    width: Annotated[float, Field(gt=0, le=100_000)] = 70
    height: Annotated[float, Field(gt=0, le=100_000)] = 70
    rotation: float = 0
    z: float | None = None
    props: dict[str, Any] = {}

    @field_validator("props")
    @classmethod
    def _props_size(cls, v: dict[str, Any]) -> dict[str, Any]:
        return _check_props(v)


class ObjectPatch(BaseModel):
    id: Id
    page_id: Id | None = None
    layer: Literal["map", "objects", "gm"] | None = None
    x: float | None = None
    y: float | None = None
    width: Annotated[float, Field(gt=0, le=100_000)] | None = None
    height: Annotated[float, Field(gt=0, le=100_000)] | None = None
    rotation: float | None = None
    z: float | None = None
    # Shallow merge into props; a key set to null is removed.
    props: dict[str, Any] | None = None

    @field_validator("props")
    @classmethod
    def _props_size(cls, v: dict[str, Any] | None) -> dict[str, Any] | None:
        return v if v is None else _check_props(v)


class ObjectCreate(_Msg):
    type: Literal["obj.create"]
    objects: Annotated[list[ObjectData], Field(min_length=1, max_length=500)]


class ObjectUpdate(_Msg):
    type: Literal["obj.update"]
    patches: Annotated[list[ObjectPatch], Field(min_length=1, max_length=500)]


class PreviewItem(BaseModel):
    id: Id
    x: float
    y: float
    rotation: float | None = None


class ObjectPreview(_Msg):
    """Transient drag positions: relayed to other viewers, never stored."""

    type: Literal["obj.preview"]
    items: Annotated[list[PreviewItem], Field(min_length=1, max_length=500)]


class ObjectDelete(_Msg):
    type: Literal["obj.delete"]
    ids: Annotated[list[Id], Field(min_length=1, max_length=500)]


class ObjectOrder(_Msg):
    type: Literal["obj.order"]
    ids: Annotated[list[Id], Field(min_length=1, max_length=500)]
    to: Literal["front", "back"]


class ChatSend(_Msg):
    type: Literal["chat.send"]
    text: Annotated[str, Field(min_length=1, max_length=4000)]


class Ping(_Msg):
    type: Literal["ping"]
    page_id: Id
    x: float
    y: float
    pull: bool = False


class TurnEntry(BaseModel):
    id: Id
    object_id: Id | None = None
    name: Annotated[str, Field(max_length=120)] = ""
    value: Annotated[str, Field(max_length=40)] = "0"


class TurnSet(_Msg):
    type: Literal["turn.set"]
    order: Annotated[list[TurnEntry], Field(max_length=200)]
    round: Annotated[int, Field(ge=0)] | None = None


class TurnAdd(_Msg):
    type: Literal["turn.add"]
    entry: TurnEntry


class TurnUpdate(_Msg):
    type: Literal["turn.update"]
    id: Id
    value: Annotated[str, Field(max_length=40)] | None = None
    name: Annotated[str, Field(max_length=120)] | None = None


class TurnRemove(_Msg):
    type: Literal["turn.remove"]
    id: Id


class TurnNext(_Msg):
    type: Literal["turn.next"]


class TurnSort(_Msg):
    type: Literal["turn.sort"]
    descending: bool = True


ClientMessage = Annotated[
    Hello
    | PlayerUpdate
    | GameSettings
    | PageView
    | PageCreate
    | PageUpdate
    | PageDelete
    | PageDuplicate
    | SetPlayerPage
    | ObjectCreate
    | ObjectUpdate
    | ObjectPreview
    | ObjectDelete
    | ObjectOrder
    | ChatSend
    | Ping
    | TurnSet
    | TurnAdd
    | TurnUpdate
    | TurnRemove
    | TurnNext
    | TurnSort,
    Field(discriminator="type"),
]
client_message: TypeAdapter[ClientMessage] = TypeAdapter(ClientMessage)


def _check_props(v: dict[str, Any]) -> dict[str, Any]:
    if len(json.dumps(v)) > MAX_PROPS_BYTES:
        raise ValueError("props too large")
    return v
